use voir_types::Span;

#[derive(Debug, Clone, PartialEq)]
pub struct Token {
    pub kind: TokenKind,
    pub span: Span,
}

#[derive(Debug, Clone, PartialEq)]
pub enum TokenKind {
    // Keywords
    Select,
    From,
    Where,
    And,
    Or,
    Not,
    As,
    Limit,
    Offset,
    Explain,
    Null,
    True,
    False,
    Distinct,
    Group,
    By,
    Having,
    Order,
    Asc,
    Desc,
    Case,
    When,
    Then,
    Else,
    End,
    Cast,
    Join,
    Inner,
    Left,
    Right,
    Full,
    Outer,
    Cross,
    On,
    Using,
    With,
    Union,
    Except,
    Intersect,
    All,
    Exists,
    In,

    // Identifiers & literals
    Ident(String),
    QuotedIdent(String),
    StringLiteral(String),
    Number(String),

    // Punctuation
    Comma,
    Star,
    Dot,
    LParen,
    RParen,
    Semicolon,

    // Operators
    Eq,
    NotEq,
    Lt,
    LtEq,
    Gt,
    GtEq,
    Plus,
    Minus,
    Slash,
    Percent,

    Eof,
}

