impl TokenKind {
    #[must_use]
    pub fn keyword_from_str(s: &str) -> Option<TokenKind> {
        match s.to_ascii_uppercase().as_str() {
            "SELECT" => Some(TokenKind::Select),
            "FROM" => Some(TokenKind::From),
            "WHERE" => Some(TokenKind::Where),
            "AND" => Some(TokenKind::And),
            "OR" => Some(TokenKind::Or),
            "NOT" => Some(TokenKind::Not),
            "AS" => Some(TokenKind::As),
            "LIMIT" => Some(TokenKind::Limit),
            "OFFSET" => Some(TokenKind::Offset),
            "EXPLAIN" => Some(TokenKind::Explain),
            "NULL" => Some(TokenKind::Null),
            "TRUE" => Some(TokenKind::True),
            "FALSE" => Some(TokenKind::False),
            "DISTINCT" => Some(TokenKind::Distinct),
            "GROUP" => Some(TokenKind::Group),
            "BY" => Some(TokenKind::By),
            "HAVING" => Some(TokenKind::Having),
            "ORDER" => Some(TokenKind::Order),
            "ASC" => Some(TokenKind::Asc),
            "DESC" => Some(TokenKind::Desc),
            "CASE" => Some(TokenKind::Case),
            "WHEN" => Some(TokenKind::When),
            "THEN" => Some(TokenKind::Then),
            "ELSE" => Some(TokenKind::Else),
            "END" => Some(TokenKind::End),
            "CAST" => Some(TokenKind::Cast),
            "JOIN" => Some(TokenKind::Join),
            "INNER" => Some(TokenKind::Inner),
            "LEFT" => Some(TokenKind::Left),
            "RIGHT" => Some(TokenKind::Right),
            "FULL" => Some(TokenKind::Full),
            "OUTER" => Some(TokenKind::Outer),
            "CROSS" => Some(TokenKind::Cross),
            "ON" => Some(TokenKind::On),
            "USING" => Some(TokenKind::Using),
            "WITH" => Some(TokenKind::With),
            "UNION" => Some(TokenKind::Union),
            "EXCEPT" => Some(TokenKind::Except),
            "INTERSECT" => Some(TokenKind::Intersect),
            "ALL" => Some(TokenKind::All),
            "EXISTS" => Some(TokenKind::Exists),
            "IN" => Some(TokenKind::In),
            _ => None,
        }
    }
}

pub(crate) fn describe(kind: &TokenKind) -> String {
    match kind {
        TokenKind::Select => "SELECT".into(),
        TokenKind::From => "FROM".into(),
        TokenKind::Where => "WHERE".into(),
        TokenKind::And => "AND".into(),
        TokenKind::Or => "OR".into(),
        TokenKind::Not => "NOT".into(),
        TokenKind::As => "AS".into(),
        TokenKind::Limit => "LIMIT".into(),
        TokenKind::Offset => "OFFSET".into(),
        TokenKind::Explain => "EXPLAIN".into(),
        TokenKind::Null => "NULL".into(),
        TokenKind::True => "TRUE".into(),
        TokenKind::False => "FALSE".into(),
        TokenKind::Distinct => "DISTINCT".into(),
        TokenKind::Group => "GROUP".into(),
        TokenKind::By => "BY".into(),
        TokenKind::Having => "HAVING".into(),
        TokenKind::Order => "ORDER".into(),
        TokenKind::Asc => "ASC".into(),
        TokenKind::Desc => "DESC".into(),
        TokenKind::Case => "CASE".into(),
        TokenKind::When => "WHEN".into(),
        TokenKind::Then => "THEN".into(),
        TokenKind::Else => "ELSE".into(),
        TokenKind::End => "END".into(),
        TokenKind::Cast => "CAST".into(),
        TokenKind::Join => "JOIN".into(),
        TokenKind::Inner => "INNER".into(),
        TokenKind::Left => "LEFT".into(),
        TokenKind::Right => "RIGHT".into(),
        TokenKind::Full => "FULL".into(),
        TokenKind::Outer => "OUTER".into(),
        TokenKind::Cross => "CROSS".into(),
        TokenKind::On => "ON".into(),
        TokenKind::Using => "USING".into(),
        TokenKind::With => "WITH".into(),
        TokenKind::Union => "UNION".into(),
        TokenKind::Except => "EXCEPT".into(),
        TokenKind::Intersect => "INTERSECT".into(),
        TokenKind::All => "ALL".into(),
        TokenKind::Exists => "EXISTS".into(),
        TokenKind::In => "IN".into(),
        TokenKind::Ident(s) | TokenKind::QuotedIdent(s) => format!("identifier `{s}`"),
        TokenKind::StringLiteral(s) => format!("string '{s}'"),
        TokenKind::Number(n) => format!("number {n}"),
        TokenKind::Comma => "','".into(),
        TokenKind::Star => "'*'".into(),
        TokenKind::Dot => "'.'".into(),
        TokenKind::LParen => "'('".into(),
        TokenKind::RParen => "')'".into(),
        TokenKind::Semicolon => "';'".into(),
        TokenKind::Eq => "'='".into(),
        TokenKind::NotEq => "'<>'".into(),
        TokenKind::Lt => "'<'".into(),
        TokenKind::LtEq => "'<='".into(),
        TokenKind::Gt => "'>'".into(),
        TokenKind::GtEq => "'>='".into(),
        TokenKind::Plus => "'+'".into(),
        TokenKind::Minus => "'-'".into(),
        TokenKind::Slash => "'/'".into(),
        TokenKind::Percent => "'%'".into(),
        TokenKind::Eof => "end of input".into(),
    }
}
